app.get('/api/me/attendances', verifyToken, async (req: Request, res: Response): Promise<any> => {
  try {
    const attSnap = await getDocs(query(collection(db, 'attendances'), where('userId', '==', req.user?.id)));
    const userAttendancesRaw = attSnap.docs.map(d => d.data());

    // Fetch events for these attendances
    const userAttendances = await Promise.all(userAttendancesRaw.map(async (a) => {
      let eventTitle = 'Unknown', eventCategory = 'Unknown';
      const evtDoc = await getDoc(doc(db, 'events', a.eventId));
      if (evtDoc.exists()) {
        const e = evtDoc.data();
        eventTitle = e.title;
        eventCategory = e.category;
      }
      return { ...a, eventTitle, eventCategory };
    }));

    const badges = computeBadges(userAttendances)

    res.json({
      attendances: userAttendances,
      stats: {
        totalAttended: userAttendances.length,
        categoryCounts: groupByCategory(userAttendances),
        badges,
      },
    })
  } catch(e) {
    console.error(e);
    res.status(500).json({ error: 'Server error' });
  }
})

const groupByCategory = (attendances: any[]) => {
  const counts: Record<string, number> = {}
  attendances.forEach((a) => {
    if (a.eventCategory) counts[a.eventCategory] = (counts[a.eventCategory] || 0) + 1
  })
  return counts
}

const computeBadges = (attendances: any[]) => {
  const badges: any[] = []
  if (attendances.length >= 5) {
    badges.push({ name: 'Community Builder', icon: '🏢', description: 'Attended 5+ events' })
  }
  const eveningEvents = attendances.filter((a) => {
    const hour = new Date(a.timestamp).getHours()
    return hour >= 18 || hour < 6
  })
  if (eveningEvents.length >= 3) {
    badges.push({ name: 'Night Owl', icon: '🌙', description: 'Attended 3+ evening events' })
  }
  const categories = groupByCategory(attendances)
  Object.entries(categories).forEach(([cat, count]) => {
    if (count >= 5) {
      badges.push({ name: `${cat} Enthusiast`, icon: '⭐', description: `Attended 5+ ${cat} events` })
    }
  })
  return badges
}

