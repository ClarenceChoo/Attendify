const handleRegister = async (req: Request, res: Response): Promise<any> => {
  const { email, name, password, role } = req.body

  if (!email || !email.endsWith('@u.nus.edu')) {
    return res.status(400).json({
      error: 'Please use a valid NUS email (@u.nus.edu)',
    })
  }
  
  if (!password || password.length < 6) {
    return res.status(400).json({ error: 'Password must be at least 6 characters long' })
  }

  try {
    const usersRef = collection(db, 'users');
    const q = query(usersRef, where('email', '==', email));
    const querySnapshot = await getDocs(q);
    
    if (!querySnapshot.empty) {
      return res.status(400).json({ error: 'User with this email already exists' })
    }

    // Hash password
    const saltRounds = 10;
    const hashedPassword = await bcrypt.hash(password, saltRounds);

    // Set role to string ('student' or 'organiser') and gracefully default to student
    const finalRole = (role === 'student' || role === 'organiser') ? role : 'student';

    // Create user with AutoID generated by addDoc
    const newUser = {
      email,
      name: name || email.split('@')[0],
      role: finalRole,
      passwordHash: hashedPassword,
      createdAt: new Date().toISOString()
    };
    
    const docRef = await addDoc(collection(db, 'users'), newUser);
    const userForToken = { id: docRef.id, ...newUser };

    // Issue JWT
    const token = jwt.sign(
      { id: userForToken.id, email: userForToken.email, role: userForToken.role },
      JWT_SECRET,
      { expiresIn: '24h' }
    )

    // Remove passwordHash before sending back
    const { passwordHash, ...safeUser } = userForToken;
    res.json({ token, user: safeUser })
  } catch (error) {
    console.error(error);
    res.status(500).json({ error: 'Server error during registration' })
  }
}

const handleLogin = async (req: Request, res: Response): Promise<any> => {
  const { email, password } = req.body

  if (!email || !password) {
    return res.status(400).json({ error: 'Email and password are required' })
  }

  try {
    const usersRef = collection(db, 'users');
    const q = query(usersRef, where('email', '==', email));
    const querySnapshot = await getDocs(q);
    
    if (querySnapshot.empty) {
      return res.status(401).json({ error: 'Invalid email or password' })
    }

    const userDoc = querySnapshot.docs[0];
    const user = { id: userDoc.id, ...userDoc.data() } as any;

    if (!user.passwordHash) {
       return res.status(401).json({ error: 'Invalid user credentials configuration. Please register again.' })
    }

    // Verify Password
    const match = await bcrypt.compare(password, user.passwordHash)
    if (!match) {
      return res.status(401).json({ error: 'Invalid email or password' })
    }

    // Issue JWT
    const token = jwt.sign(
      { id: user.id, email: user.email, role: user.role },
      JWT_SECRET,
      { expiresIn: '24h' }
    )

    const { passwordHash, ...safeUser } = user;
    res.json({ token, user: safeUser })
  } catch (error) {
    console.error(error);
    res.status(500).json({ error: 'Server error during login' })
  }
}

app.post('/api/auth/register', handleRegister);
app.post('/api/auth/login', handleLogin);

// Verify token middleware
const verifyToken = (req: Request, res: Response, next: NextFunction): any => {
  const token = req.headers.authorization?.split(' ')[1]

  if (!token) {
    return res.status(401).json({ error: 'No token provided' })
  }

  try {
    const decoded = jwt.verify(token, JWT_SECRET) as UserPayload
    req.user = decoded
    next()
  } catch (error) {
    res.status(401).json({ error: 'Invalid token' })
  }
}

